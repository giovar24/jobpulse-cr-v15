-- 023_taxonomia_curacion_tanda_1.sql
-- CURACION DE LA TAXONOMIA, TANDA 1 (Ola 4.2).
--
-- MOTIVACION (objetivo del software): encontrar, entre TODOS los puestos, los
-- que tienen requisitos mas compatibles con la persona del CV. Para comparar
-- un requisito del aviso con un hecho del perfil, los dos tienen que hablar
-- el mismo idioma: la tabla `concepto` (variante de texto -> codigo
-- canonico). El motor SOLO compara los requisitos CON `codigo_canonico`
-- (`AND codigo_canonico IS NOT NULL`): los demas se IGNORAN en silencio.
--
-- AUDIT del corpus real (2026-11-06, 3397 skills distintas / 5199 menciones):
--   * solo 241 resolvian a un concepto (877 menciones: el 17%);
--   * 1634 eran RUIDO (actividad, palabra vacia o sector) y se descartan
--     antes de encolar (`conceptos.es_variante_encolable`);
--   * 1522 quedaban EN LA COLA: variantes que el corpus pide y la taxonomia
--     no cubria. Esta migracion curada las mas Demandadas.
--
-- Que hace esta migracion:
--   1. ALIAS de conceptos que YA existen: el aviso nombra la misma
--      competencia de otra forma ("office 365 basico" es Office 365;
--      "mantenimiento correctivo" es mantenimiento). Sin estos alias, el
--      requisito queda SIN codigo -> el motor lo ignora -> la vacante parece
--      mas compatible de lo que es.
--   2. CONCEPTOS NUEVOS: herramientas y metodos concretos que el corpus pide
--      y no tenian ningun codigo (Mulesoft, PowerShell, MFA, ISO 9001,
--      lectura de planos, metrologia, cableado estructurado...).
--
-- REGLAS que respeta (las mismas de la migracion 021):
--   * Solo variantes en minusculas, sin acentos y con espacios simples: el
--     resolver de `conceptos` compara `LOWER(TRIM(value_code))` y el modulo
--     `skills_fuente` normaliza igual (minusculas, sin acentos).
--   * Las variantes NO son codigos: el codigo canonico agrupa las sinonimas.
--   * Idempotente: solo agrega filas que faltan (PRIMARY KEY
--     (categoria, variante)).
--
-- Criterio de curacion (2026-11-06): solo entra lo que nombra una
-- COMPETENCIA, una HERRAMIENTA, una NORMA o un METODO concreto. Se deja
-- fuera lo que es una funcion ("ventas"), un sector ("construccion"), una
-- palabra vacia ("analysis", "planning") o una tarea ("despachar",
-- "empacar"): contarlas como competencia penaliza a todos los avisos por
-- igual y esconde los gaps reales.

